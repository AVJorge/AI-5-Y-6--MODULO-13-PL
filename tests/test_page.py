# Prueba automatizada del material AI5-AI6. Uso: python tests/test_page.py RUTA_DE_LA_CARPETA [CARPETA_CAPTURAS]
import sys, os, tempfile
from playwright.sync_api import sync_playwright
root = sys.argv[1]
shots = sys.argv[2] if len(sys.argv) > 2 else tempfile.mkdtemp()
errors, fails = [], []
def check(cond, msg):
    (print("OK  ", msg) if cond else (fails.append(msg), print("FAIL", msg)))
def pmt(P, i, n): return P*i/(1-(1+i)**-n)
num = lambda s: float(s.replace('\xa0','').replace(' ','').replace('$','').replace('−','-').replace(',',''))
with sync_playwright() as p:
    exe = os.environ.get("CHROME_PATH")
    b = p.chromium.launch(executable_path=exe) if exe else p.chromium.launch()
    for vw in [(1280,900),(390,844)]:
        pg = b.new_page(viewport={"width":vw[0],"height":vw[1]})
        pg.on("pageerror", lambda e: errors.append(str(e)))
        pg.goto(f"file://{root}/index.html"); pg.wait_for_timeout(300)
        print(f"--- viewport {vw}")
        txt = lambda s: pg.text_content(s).replace('\xa0',' ').strip()
        check(pg.is_visible("#act5") and not pg.is_visible("#act6"), "AI5 visible por defecto")
        # --- Presupuesto Ruiz
        check(txt("#kMeta")=="$27 600", "meta 24 x 1 150")
        check(txt("#kIng")=="$246 000", f"ingresos anuales ({txt('#kIng')})")
        egr = 12*15900 + 6*1100
        check(num(txt("#kEgr"))==egr, f"egresos anuales ({txt('#kEgr')} vs {egr})")
        check("julio" in txt("#kMes"), f"meta alcanzada en julio ({txt('#kMes')})")
        check(pg.locator("#tRuiz td.reach").count()==1, "celda del mes de la meta resaltada")
        pg.evaluate("()=>{const e=document.getElementById('eAli');e.value=4000;e.dispatchEvent(new Event('input'))}")
        pg.evaluate("()=>{const e=document.getElementById('eOtr');e.value=0;e.dispatchEvent(new Event('input'))}")
        check("mayo" in txt("#kMes"), f"con menos gastos alcanza en mayo ({txt('#kMes')})")
        pg.evaluate("()=>{const e=document.getElementById('eAli');e.value=6500;e.dispatchEvent(new Event('input'))}")
        pg.evaluate("()=>{const e=document.getElementById('eOtr');e.value=3000;e.dispatchEvent(new Event('input'))}")
        check("No en este año" in txt("#kMes") and pg.locator("#tRuiz td.reach").count()==0, "con más gastos no alcanza")
        check("NaN" not in pg.inner_html("#cRuiz"), "gráfica Ruiz sin NaN")
        # --- Anualidad
        R = pmt(18000, .01, 12)
        check(abs(num(txt("#aR1"))-R)<0.01, f"pago 18 000 al 12% en 12 meses ({txt('#aR1')} vs {R:.2f})")
        check(abs(num(txt("#aInt"))-(R*12-18000))<0.02, "intereses totales")
        check("1 680.00" in txt("#aWrong"), "atajo incorrecto (interés simple / 12)")
        pg.select_option("#aR","18"); pg.select_option("#aN","24")
        pg.evaluate("()=>{const e=document.getElementById('aP');e.value=30000;e.dispatchEvent(new Event('input'))}")
        R2 = pmt(30000, .015, 24)
        check(abs(num(txt("#aR1"))-R2)<0.01, f"pago 30 000 al 18% en 24 meses ({R2:.2f})")
        check(pg.locator("#cAnu rect").count()==48, "24 barras divididas en interés y capital")
        check(pg.evaluate("()=>[...document.getElementById('aR').options].every(o=>o.value!=='9')"), "no hay tasa de 9 %")
        pg.evaluate("()=>{const e=document.getElementById('aP');e.value=33810;e.dispatchEvent(new Event('input'))}")
        check(pg.input_value("#aP")=="30000", "el monto no acepta 33 810")
        # --- Hojas AI5
        for k in "1234":
            pg.click(f"#s5Tabs button[data-s='{k}']")
            empty = pg.evaluate("""()=>[...document.querySelectorAll('#sheet5 td.f')].filter(td=>{td.click();return !document.getElementById('fexp5').textContent}).map(t=>t.textContent)""")
            check(not empty, f"hoja {k}: todas las fórmulas tienen explicación {empty}")
        pg.locator("#qz5 .q").nth(1).locator("button").nth(1).click()
        check("Correcto" in pg.locator("#qz5 .fb").nth(1).text_content(), "quiz AI5")
        for c in pg.locator("#check5 input").all(): c.check()
        check("Listo" in txt("#lista5 .ptext"), "lista AI5")
        ov = pg.evaluate("document.documentElement.scrollWidth - window.innerWidth")
        check(ov<=1, f"AI5 sin desbordamiento ({ov}px)")
        pg.screenshot(path=f"{shots}/ai5_{vw[0]}.png", full_page=True)
        # --- AI6
        pg.click("#sw-ai6"); pg.wait_for_timeout(150)
        check(pg.is_visible("#act6") and not pg.is_visible("#act5") and pg.evaluate("scrollY")==0, "selector muestra AI6 arriba")
        cards = [num(x.split('+')[0].split(')')[-1]) for x in pg.locator("#capCards .capcard").all_text_contents()]
        exp = [40000*(1+.07/m)**m for m in (1,2,4,12)]
        check(all(abs(a-b)<0.01 for a,b in zip(cards,exp)), f"capitalización 7 % ({cards})")
        check("Mensual" in pg.locator("#capCards .top").text_content(), "mensual rinde más")
        check(txt("#instBody tr:first-child td:nth-child(6)")=="—", "rendimientos ocultos antes de calcular")
        pg.click("#iCalc")
        rend = {r[0]: num(r[6]) for r in [ [c.strip() for c in row.split('\t')] for row in pg.evaluate("()=>[...document.querySelectorAll('#instBody tr')].map(tr=>[...tr.cells].map(c=>c.textContent).join('\\t'))")]}
        check(abs(rend['Fondo Horizonte']-3492.43)<0.01 and abs(rend['Banco Norte']-3000)<0.01, f"rendimientos ({rend})")
        check("Fondo Horizonte" in txt("#instBody tr.pick"), "cualquier riesgo: Fondo Horizonte")
        pg.click("#riskPick button[data-k='1']")
        check("Banco Norte" in txt("#instBody tr.pick") and pg.locator("#instBody tr.dim").count()==2, "solo riesgo bajo: Banco Norte")
        check("Renuncias" in txt("#iMsg"), "explica lo que se renuncia por menos riesgo")
        # enganche y amortización (Banco Norte -> 43 000)
        F = 210000-43000
        check("167 000.00" in txt("#flow"), f"monto financiado ({txt('#flow')[-40:]})")
        R3 = pmt(F, .03, 24)
        check(f"{R3:,.2f}".replace(',',' ') in txt("#tPay") and "no se divide" in txt("#tPay"), f"pago 24 meses al 3 % mensual ({R3:.2f})")
        pg.click("#tNext"); pg.click("#tNext")
        r2 = [c for c in pg.locator("#tBody tr").nth(1).locator("td").all_text_contents()]
        ini2 = F - (R3 - F*.03)
        check(abs(num(r2[1])-ini2)<0.01 and abs(num(r2[3])-ini2*.03)<0.01, "mes 2: saldo e interés")
        pg.select_option("#tN","48"); pg.click("#tAll")
        check(pg.locator("#tBody tr").count()==48, "48 renglones")
        last = pg.locator("#tBody tr").nth(47).locator("td").nth(5).text_content()
        check(last.replace('\xa0',' ')=="$0.00", f"saldo final en cero ({last})")
        check(pg.locator("#tFoot tr").count()==3 and "Costo total" in txt("#tFoot"), "totales al completar la tabla")
        R48 = pmt(F,.03,48); R24 = R3
        vs = txt("#vsPlazos")
        check(f"{R48:,.2f}".replace(',',' ') in vs and f"{R24:,.2f}".replace(',',' ') in vs, "comparación 24 vs 48")
        check(pg.evaluate("()=>[...document.getElementById('tR').options].every(o=>o.value!=='12')"), "no hay tasa de 12 % en la tabla")
        pg.click("#s6Tabs button[data-s='2']")
        check("=PAGO(B4,B5,-B3)" in pg.text_content("#sheet6") and "/12" not in pg.text_content("#sheet6"), "hoja de amortización sin dividir entre 12")
        pg.click("#s6Tabs button[data-s='1']")
        for k in "12":
            pg.click(f"#s6Tabs button[data-s='{k}']")
            empty = pg.evaluate("""()=>[...document.querySelectorAll('#sheet6 td.f')].filter(td=>{td.click();return !document.getElementById('fexp6').textContent}).map(t=>t.textContent)""")
            check(not empty, f"AI6 hoja {k}: fórmulas con explicación {empty}")
        pg.locator("#qz6 .q").nth(2).locator("button").nth(0).click()
        check("Correcto" in pg.locator("#qz6 .fb").nth(2).text_content(), "quiz AI6")
        for c in pg.locator("#check6 input").all(): c.check()
        check("Listo" in txt("#lista6 .ptext"), "lista AI6")
        ov = pg.evaluate("document.documentElement.scrollWidth - window.innerWidth")
        check(ov<=1, f"AI6 sin desbordamiento ({ov}px)")
        pg.screenshot(path=f"{shots}/ai6_{vw[0]}.png", full_page=True)
        # navegación
        pg.goto(f"file://{root}/index.html#amortizacion"); pg.wait_for_timeout(200)
        check(pg.is_visible("#act6"), "enlace directo a sección de AI6")
        pg.goto(f"file://{root}/index.html#ai5"); pg.wait_for_timeout(300)
        check(pg.is_visible("#act5") and pg.evaluate("scrollY")==0, "enlace #ai5 abre arriba")
        dup = pg.evaluate("()=>{const c={};document.querySelectorAll('[id]').forEach(e=>c[e.id]=(c[e.id]||0)+1);return Object.keys(c).filter(k=>c[k]>1)}")
        broken = pg.evaluate("()=>[...document.querySelectorAll('a[href^=\"#\"]')].map(a=>a.getAttribute('href').slice(1)).filter(h=>!document.getElementById(h)&&!['ai5','ai6'].includes(h))")
        check(not dup and not broken, f"sin IDs duplicados ni enlaces rotos {dup} {broken}")
        pg.close()
    b.close()
print("\nErrores JS:", errors or "ninguno")
print("Fallas:", fails or "ninguna")
sys.exit(1 if (errors or fails) else 0)
